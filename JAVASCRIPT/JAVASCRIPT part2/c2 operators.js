//Arithmetic Operator
let a=10;
let b=5;
console.log(a+b);
console.log(a-b);
console.log(a*b);
console.log(a/b);
console.log(a%b);
console.log(a**b);

//unary operator
console.log(a++);
console.log(++a);

//Comparison operator:- (>,>=,<,<=,==,!=,===)
let age=18;
console.log(age>18);
console.log(age>=18);
console.log(age<18);
console.log(age<=18);
console.log(age==18);
console.log(age!=18);
console.log(age==="18");

//Logical operator:-&&,||,!
let marks=85;
if(marks>33 && marks<=90) {
    console.log("pass");
}