// do something}

for(let i=1;i<=5;i++){
    console.log(i);
}
for(let j=5;j>=1;j--){
    console.log(j);
}

//print all odd no.s from 1 to 15
for(let k=1;k<=15;k=k+2){
    console.log(k);
}

//print all even no.s from 2 to 10
for(let n=2;n<=10;n=n+2){
    console.log(n);
}

//print multiplication of 5
for(let z=5;z<=50;z=z+5){
    console.log(z);
}

